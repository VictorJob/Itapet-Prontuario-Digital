grant usage on schema public to authenticated;
grant select, insert, update, delete on public.tutor, public.clinica, public.pet,
  public.veterinario, public.clinicas_e_pets, public.historico, public.lembrete,
  public.pet_peso, public.documentos to authenticated;
do $$
declare
  v_table text;
  sequence_name text;
begin
  foreach v_table in array array['tutor', 'clinica', 'pet', 'veterinario', 'historico', 'lembrete', 'pet_peso', 'documentos'] loop
    sequence_name := pg_get_serial_sequence(format('public.%I', v_table), 'cod');
    if sequence_name is not null then
      execute format('grant usage, select on sequence %s to authenticated', sequence_name);
    end if;
  end loop;
end;
$$;

