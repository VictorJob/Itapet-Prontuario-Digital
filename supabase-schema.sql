-- Itapet schema and browser-client security policies.
-- Run in Supabase SQL Editor. Existing tables are extended without replacing data.

create table if not exists public.tutor (
  cod integer generated by default as identity primary key,
  nome text not null,
  email text not null,
  senha text,
  telefone text
);

create table if not exists public.clinica (
  cod integer generated by default as identity primary key,
  clinica integer,
  nome text not null,
  cnpj text,
  email text not null,
  senha text,
  endereco text,
  cep text,
  telefone text
);

create table if not exists public.pet (
  cod integer generated by default as identity primary key,
  cod_tutor integer references public.tutor(cod) on delete cascade,
  nome text not null,
  especie text,
  raca text,
  sexo text,
  pelagem text,
  cod_coleira text,
  nascimento date,
  foto text
);

create table if not exists public.veterinario (
  cod integer generated by default as identity primary key,
  cod_clinica integer references public.clinica(cod) on delete cascade,
  nome text not null,
  crmv text not null,
  email text not null,
  especialidade text
);

create table if not exists public.clinicas_e_pets (
  cod_clinica integer references public.clinica(cod) on delete cascade,
  cod_pet integer references public.pet(cod) on delete cascade,
  primary key (cod_clinica, cod_pet)
);

create table if not exists public.historico (
  cod integer generated by default as identity primary key,
  cod_pet integer not null references public.pet(cod) on delete cascade,
  cod_veterinario integer references public.veterinario(cod) on delete set null,
  tipo text,
  diagnostico_motivo text,
  sintomas text,
  tratamento text,
  nome_clinica text,
  peso numeric,
  data date not null default current_date
);

create table if not exists public.lembrete (
  cod integer generated by default as identity primary key,
  cod_pet integer not null references public.pet(cod) on delete cascade,
  cod_veterinario integer references public.veterinario(cod) on delete set null,
  titulo text not null,
  tipo text,
  detalhe text,
  data date not null,
  hora time,
  agendado_por_clinica boolean not null default false
);

create table if not exists public.pet_peso (
  cod integer generated by default as identity primary key,
  pet_cod integer not null references public.pet(cod) on delete cascade,
  peso numeric not null check (peso > 0),
  data date not null default current_date
);

create table if not exists public.documentos (
  cod integer generated by default as identity primary key,
  cod_historico integer not null references public.historico(cod) on delete cascade,
  documento text not null,
  data date not null default current_date
);

