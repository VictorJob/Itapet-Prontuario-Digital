do $$
declare
  v_table text;
  max_id integer;
  identity_sequence text;
begin
  foreach v_table in array array['tutor', 'clinica', 'pet', 'veterinario', 'historico', 'lembrete', 'pet_peso', 'documentos'] loop
    if exists (
      select 1 from information_schema.columns c
      where c.table_schema = 'public' and c.table_name = v_table and c.column_name = 'cod'
        and c.column_default is null and c.is_identity = 'NO'
    ) then
      execute format('alter table public.%I alter column cod add generated by default as identity', v_table);
      execute format('select max(cod) from public.%I', v_table) into max_id;
      identity_sequence := pg_get_serial_sequence(format('public.%I', v_table), 'cod');
      if identity_sequence is not null then
        perform setval(identity_sequence, greatest(coalesce(max_id, 1), 1), max_id is not null and max_id > 0);
      end if;
    end if;
  end loop;
end;
$$;

