drop policy if exists "pets visible to their tutor or clinic" on public.pet;
create policy "pets visible to their tutor or clinic" on public.pet for select to authenticated
  using (
    exists (select 1 from public.tutor t where t.cod = pet.cod_tutor and t.auth_user_id = (select auth.uid()))
    or exists (
      select 1 from public.clinicas_e_pets cp join public.clinica c on c.cod = cp.cod_clinica
      where cp.cod_pet = pet.cod and c.auth_user_id = (select auth.uid())
    )
  );
